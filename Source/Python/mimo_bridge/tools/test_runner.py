# ------------------------------------------------------------------------------------------ the machine's processes
def _norm(text) -> str:
    return str(text).replace("\\", "/")


def scan_processes() -> list:
    """Every process of the machine as {pid, ppid, created, name, cmdline (a list, slashes forward)}; a process that
    cannot be read is left out. The environment is read later and only for the processes the audit judges."""
    import psutil
    out = []
    for p in psutil.process_iter(["pid", "ppid", "name", "cmdline", "create_time"]):
        try:
            info = p.info
            out.append(dict(pid=info["pid"], ppid=info["ppid"], created=info["create_time"],
                            name=(info["name"] or "").lower(), cmdline=[_norm(a) for a in (info["cmdline"] or [])]))
        except Exception:
            continue
    return out


def read_marks(pid) -> dict:
    """{UEMA_TEST_ROW, UEMA_TEST_RUN, UEMA_DEV_RUN} as process `pid` carries them (only the ones it has); {} when the
    process is gone or its environment cannot be read."""
    try:
        import psutil
        env = psutil.Process(int(pid)).environ()
    except Exception:
        return {}
    return {k: env[k] for k in (ENV_ROW, ENV_RUN, ENV_DEV) if env.get(k)}


def is_python(process) -> bool:
    name = process.get("name") or ""
    return any(name.startswith(n) for n in PYTHON_NAMES)


def alive(pid, created, processes=None) -> bool:
    """True while process `pid` runs and is the same process (its creation time within 1 s of `created`; a process
    id is reused by Windows). With `processes` (a scan) the answer comes from the scan."""
    if pid is None:
        return False
    if processes is not None:
        found = next((p for p in processes if p["pid"] == int(pid)), None)
        return found is not None and (created is None or abs(found["created"] - float(created)) < 1.0)
    now = tr.process_created(pid)
    return now is not None and (created is None or abs(now - float(created)) < 1.0)


def is_trainer(process) -> bool:
    """A python process that IS a trainer: `-m mimo_bridge.train_mimo` or the script mimo_bridge/train_mimo.py among
    its arguments (the test of run_jobs_in_held_pause.trainer_running)."""
    if not is_python(process):
        return False
    args = process.get("cmdline") or []
    return TRAINER_MODULE in args or any(a.endswith("mimo_bridge/train_" + "mimo.py") for a in args)


def trainer_runs(process) -> list:
    """The names of the run folders under Saved/mimo_bridge/experiments a trainer's command line names."""
    out = []
    for a in process.get("cmdline") or []:
        low = a.lower()
        at = low.find(EXPERIMENTS.lower() + "/")
        if at >= 0:
            name = a[at + len(EXPERIMENTS) + 1:].split("/")[0]
            if name and name not in out:
                out.append(name)
    return out


def production_trainers(processes) -> list:
    """The trainer processes whose command line names a run folder under Saved/mimo_bridge/experiments (the test of
    the agents' capped runner, Oct 4, 2026: a unit test's short trainer names a test folder and is not one). A
    process whose parent is one too is the same trainer (the Windows venv launcher and its child)."""
    found = [p for p in processes if is_trainer(p) and trainer_runs(p)]
    ids = {p["pid"] for p in found}
    return [p for p in found if p["ppid"] not in ids]


def _script_names(process) -> list:
    return [a.rsplit("/", 1)[-1] for a in process.get("cmdline") or [] if a.lower().endswith(".py")]


def _matches(name, patterns) -> bool:
    return any(fnmatch.fnmatch(name, pattern) for pattern in patterns)


def legacy_runner_row(process):
    """The row id a runner of the older kind runs: `<...>_registry.py run ROW_ID ...` (or registry_rows.py) on the
    process's command line, else None. Such a runner writes status running without a process id."""
    args = process.get("cmdline") or []
    for i, a in enumerate(args):
        if a.lower().endswith(".py") and _matches(a.rsplit("/", 1)[-1], LEGACY_RUNNER_SCRIPTS):
            rest = args[i + 1:]
            if len(rest) >= 2 and rest[0] == "run":
                return rest[1]
    return None


def is_legacy_capped(process) -> bool:
    """A runner of the older kind in its development form: `<...>_registry.py capped -- COMMAND`."""
    args = process.get("cmdline") or []
    for i, a in enumerate(args):
        if a.lower().endswith(".py") and _matches(a.rsplit("/", 1)[-1], LEGACY_RUNNER_SCRIPTS):
            return args[i + 1:i + 2] == ["capped"]
    return False


def scheduled_task(process):
    """The ability scheduler's task id of a process it started: the folder name of its --out argument,
    <task>_<step>_attempt<n>_<time>, else None."""
    args = process.get("cmdline") or []
    if "--out" in args[:-1]:
        match = SCHEDULED_OUTPUT.match(args[args.index("--out") + 1].rstrip("/").rsplit("/", 1)[-1])
        if match:
            return match.group("task")
    return None


def is_test_runner(process) -> bool:
    """A process that IS this module's command line (python -m mimo_bridge.tools.test_runner ..., or its file run as
    a script): the runner of a row, a development run's starter or an audit. It is never itself a test process: the
    job it starts carries the row's marks (or the development run's)."""
    args = process.get("cmdline") or []
    own = args[:args.index("--")] if "--" in args else args
    return any(own[i] == "-m" and own[i + 1] == "mimo_bridge.tools.test_runner" for i in range(len(own) - 1)) or \
        any(a.endswith("mimo_bridge/tools/test_runner.py") for a in own[1:2])


def signature_of(process):
    """Why a process without a mark is a test process (TEST SIGNATURES in the module text), or None. Only the
    process's own part of its command line is read: the arguments after a "--" are the command a wrapper starts, and
    that command's own process is judged by itself."""
    if not is_python(process):
        return None
    args = process.get("cmdline") or []
    if is_trainer(process):
        return None if trainer_runs(process) else "a trainer whose command line names no production run folder"
    own = args[:args.index("--")] if "--" in args else args
    if (process.get("name") or "").startswith("pytest") or any(
            own[i] == "-m" and own[i + 1] in ("pytest", "py.test") for i in range(len(own) - 1)):
        return "pytest"
    for a in own[1:]:
        if TEST_FOLDER.search(a) and not _matches(a.rsplit("/", 1)[-1], NOT_TEST_SCRIPTS):
            return "a script of a test folder (%s)" % a.rsplit("/", 1)[-1]
    return None


def named_run(row):
    """The production run folder's name a row names: last_run.production_run, else the run folder inside its
    last_run's log or receipt path (Saved/mimo_bridge/experiments/<run>/...); None when it names none."""
    last = row.get("last_run") if isinstance(row.get("last_run"), dict) else {}
    if last.get("production_run"):
        return _norm(last["production_run"]).rstrip("/").rsplit("/", 1)[-1]
    for key in ("log", "receipt"):
        text = _norm(last.get(key) or "")
        at = text.lower().find(EXPERIMENTS.lower() + "/")
        if at >= 0:
            name = text[at + len(EXPERIMENTS) + 1:].split("/")[0]
            if name:
                return name
    return None


def _read_json(path) -> dict:
    try:
        value = json.loads(Path(path).read_text(encoding="utf-8-sig"))
        return value if isinstance(value, dict) else {}
    except (OSError, ValueError):
        return {}


def training_hold(root=None) -> dict:
    """WHY NO PRODUCTION TRAINER RUNS, from the records of the data checkout `root` (Saved/mimo_bridge):
    {reason, source, active_run, held_at_step, since, since_text, supervisor_cmd}. reason: supervisor_control.json's
    reason while its cmd is pause; else the active run's stop_reason.json; else training_continuation.json's
    pause_reason; else None (no hold is on record). held_at_step and since: the active run's stage_done.json (the
    model step training stopped at, and when)."""
    saved = Path(root or tr.REPO) / "Saved" / "mimo_bridge"
    control = _read_json(saved / "supervisor_control.json")
    continuation = _read_json(saved / "training_continuation.json")
    active = _norm(continuation.get("active_run") or "").rstrip("/")
    run = Path(active) if active else None
    stop = _read_json(run / "stop_reason.json") if run else {}
    done = _read_json(run / "stage_done.json") if run else {}
    reason = source = None
    if control.get("cmd") == "pause" and str(control.get("reason") or "").strip():
        reason, source = str(control["reason"]).strip(), "supervisor_control.json"
    elif str(stop.get("reason") or "").strip():
        reason, source = str(stop["reason"]).strip(), "the active run's stop_reason.json"
    elif str(continuation.get("pause_reason") or "").strip():
        reason, source = str(continuation["pause_reason"]).strip(), "training_continuation.json"
    since = done.get("finished_at") if isinstance(done.get("finished_at"), (int, float)) else None
    return dict(reason=reason, source=source, active_run=run.name if run else None,
                held_at_step=done.get("steps") if isinstance(done.get("steps"), int) else None, since=since,
                since_text=None if since is None else tr.clock(since), supervisor_cmd=control.get("cmd"))


def held_text(hold) -> str:
    """One sentence for a hold (training_hold): no trainer is alive, where training stopped, and the reason on
    record with its file, or that none is on record."""
    hold = hold or {}
    where = ""
    if hold.get("held_at_step") is not None:
        where = " Training stopped at model step %s%s%s." % (
            format(hold["held_at_step"], ","), " of run %s" % hold["active_run"] if hold.get("active_run") else "",
            " (%s)" % hold["since_text"] if hold.get("since_text") else "")
    reason = ("Reason on record (%s): %s." % (hold["source"], str(hold["reason"]).rstrip("."))
              if hold.get("reason") else "No reason for the hold is on record.")
    return "no production trainer process is alive.%s %s" % (where, reason)


# ------------------------------------------------------------------------------------------ the baseline
def baseline_path(code_root=None) -> Path:
    return Path(code_root or tr.REPO) / BASELINE_RELATIVE


def _record_digest(row) -> str:
    import hashlib
    text = json.dumps([row.get("status"), row.get("last_run")], sort_keys=True, ensure_ascii=False, default=str)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def make_baseline(data, seal_required_from=None, now=None) -> dict:
    """The rows whose status is the runner's (running, done, failed) and whose last_run carries no verified seal, as
    they stand in `data`: {taken_at, seal_required_from, rows: {id: digest of [status, last_run]}}. The audit accepts
    exactly these; a later change of such a row's status without a seal is reported."""
    rows = {}
    for row in data.get("rows", []):
        if isinstance(row, dict) and isinstance(row.get("id"), str) and row.get("status") in tr.RUNNER_STATUSES \
                and not tr.sealed(row):
            rows[row["id"]] = _record_digest(row)
    return dict(about="Rows of the test registry whose runner status carries no seal, as they stood when this file "
                      "was written (test_runner baseline --write). test_runner.audit() accepts these as they are.",
                taken_at=tr.clock(now), seal_required_from=seal_required_from, rows=rows)


def load_baseline(code_root=None) -> dict:
    try:
        data = json.loads(baseline_path(code_root).read_text(encoding="utf-8-sig"))
        return data if isinstance(data, dict) and isinstance(data.get("rows"), dict) else {}
    except (OSError, ValueError):
        return {}


# ------------------------------------------------------------------------------------------ the audit
# what the audit recognizes as a test process, in the words its sentence carries (TEST SIGNATURES in the module text)
SEEN_TEXT = ("A test process here is a process carrying a row's mark, one under a runner of the older kind, the "
             "ability scheduler or a pause runner, pytest, a script of a docs/gain_of_function_v<N> folder, or a "
             "trainer that names no production run; a test started otherwise (a script in another folder, python -c) "
             "is not seen by this audit.")
WRITING_END_S = 120.0       # a runner writes a job's end within seconds of the job's last process (finding L1)


def unsealed_judgement(row_id, row, baseline):
    """("unverified", text) for a runner status without the seal that stands as the baseline's own list holds it
    (rows as they stood before the seal existed: accepted as they stood, and listed); else ("error", text): ANY OTHER
    UNSEALED RUNNER STATUS IS AN ERROR, whatever date its last run carries (the dashboard review of Oct 5, 2026, finding
    F5: a status typed with a back-dated last run read "unverified" and its row DONE)."""
    status = row.get("status")
    last = row.get("last_run") if isinstance(row.get("last_run"), dict) else {}
    if (baseline or {}).get("rows", {}).get(row_id) == _record_digest(row):
        return "unverified", ("Row %s says %s from a last run without the runner's seal, as it stood in the baseline of "
                              "%s (written by %s): accepted as it stood; it cannot be told from a hand edit."
                              % (row_id, status, baseline.get("taken_at") or "no time",
                                 last.get("runner") or "no runner named"))
    return "error", ("Row %s says %s, and its last run carries no verified seal of the runner%s and is not in the "
                     "baseline's list of rows as they stood before the seal: the status was written by hand, by a "
                     "runner of the older kind after the baseline, or its last run was edited after the runner wrote "
                     "it." % (row_id, status, "" if last else " (it has no last run at all)"))


def holds_run(hold, run_name) -> bool:
    """True when the hold on record (training_hold) is a hold of run `run_name`: the run training is held in is that
    run (the dashboard review of Oct 5, 2026, finding L3: a segment of an earlier run read HELD)."""
    return bool(run_name) and (hold or {}).get("active_run") == run_name


def timeout_refusal(timeout_s, row_limit):
    """Why --timeout may not be used for a row, or None: it may shorten the row's own time limit (cost.time_limit_s),
    never lengthen it (the dashboard review of Oct 5, 2026, finding L2)."""
    if timeout_s and row_limit is not None and float(timeout_s) > float(row_limit):
        return ("--timeout %s s is above the row's own time limit of %s s (cost.time_limit_s); change the row through "
                "its writers to run longer" % (tr._number_text(timeout_s), tr._number_text(row_limit)))
    return None


def writing_end_over(row_id, last, rows, now):
    """Why a running row whose job process is gone, under a runner that is still alive, cannot still be having its end
    written (the dashboard review of Oct 5, 2026, finding L1), or None: the same runner process (process id and
    creation time) has since started another row's job, or the job is past its own time limit by WRITING_END_S."""
    started = last.get("started_at") if tr._number(last.get("started_at")) else tr.parse_clock(last.get("started"))
    for other_id, other in rows.items():
        o = other.get("last_run") if other_id != row_id and isinstance(other.get("last_run"), dict) else None
        if not o or other.get("status") != "running" or o.get("runner_pid") != last.get("runner_pid"):
            continue
        if o.get("runner_pid_created") is not None and last.get("runner_pid_created") is not None and \
                abs(float(o["runner_pid_created"]) - float(last["runner_pid_created"])) >= 1.0:
            continue
        o_started = o.get("started_at") if tr._number(o.get("started_at")) else tr.parse_clock(o.get("started"))
        if started is not None and o_started is not None and o_started > started:
            return ("its runner process %s started the job of row %s at %s, so it is not writing this row's end"
                    % (last.get("runner_pid"), other_id, tr.clock(o_started)))
    cost = rows.get(row_id, {}).get("cost") if isinstance(rows.get(row_id), dict) else None
    limit = (cost or {}).get("time_limit_s") if isinstance(cost, dict) else None
    if started is not None and tr._number(limit) and now > started + float(limit) + WRITING_END_S:
        return ("the run started %s and its time limit of %s s ended more than %d s ago, so its runner is not writing "
                "its end" % (tr.clock(started), tr._number_text(limit), int(WRITING_END_S)))
    return None


def _short(cmdline, limit=220) -> str:
    text = " ".join(cmdline or [])
    return text if len(text) <= limit else text[:limit - 3] + "..."


def audit(path=None, data=None, root=None, now=None, processes=None, marks=None, code_root=None) -> dict:
    """The watchdog of directive section 8, both directions, read now: see AUDIT in the module text.

    Returns {available, ok, read_at_text, sentence, mismatches [{kind, row, pid, text}], running_rows [{id, alive,
    how}], test_processes [{pid, row, run_id, how, command}], development_runs [{pid, owner, purpose, command}],
    unverified [{row, text}], trainers [{pid, runs}]}. `processes` (a scan_processes() list) and `marks` (a function
    pid -> the marks it carries) replace the machine's own for a test; `root` holds Saved/ (the active run)."""
    now = time.time() if now is None else float(now)
    root = Path(root or tr.REPO)
    path = Path(path or tr.registry_path(root))
    if data is None:
        data = tr.load(path)
    processes = scan_processes() if processes is None else processes
    marks = read_marks if marks is None else marks
    by_pid = {p["pid"]: p for p in processes}
    rows = {r["id"]: r for r in data.get("rows", []) if isinstance(r, dict) and isinstance(r.get("id"), str)}
    mismatches, running_rows, test_processes, development, unverified = [], [], [], [], []

    def chain(p):
        """The process and its parents, nearest first (a parent started after its child is a reused id: stop)."""
        out, seen = [], set()
        while p is not None and p["pid"] not in seen:
            out.append(p)
            seen.add(p["pid"])
            parent = by_pid.get(p["ppid"])
            if parent is None or parent["created"] > p["created"] + 1.0:
                break
            p = parent
        return out

    trainers = production_trainers(processes)
    trainer_ids = set()
    for t in trainers:
        trainer_ids.add(t["pid"])
    candidates = [p for p in processes if is_python(p)]
    marked = {p["pid"]: marks(p["pid"]) for p in candidates}
    found_rows = {}        # row id -> [how a live process was matched to it]

    def note_row(row_id, how):
        found_rows.setdefault(row_id, []).append(how)

    seen_tests = set()
    for p in candidates:
        mine = marked.get(p["pid"]) or {}
        line = chain(p)
        parent = by_pid.get(p["ppid"])
        if parent is not None and parent["pid"] in marked and parent.get("cmdline") == p.get("cmdline") \
                and (marked.get(parent["pid"]) or {}) == mine:
            continue                        # the Windows venv launcher's child: the same process, judged at its parent
        if mine.get(ENV_ROW):
            row_id, run_id = mine[ENV_ROW], mine.get(ENV_RUN)
            key = ("row", row_id, run_id)
            note_row(row_id, "a process carrying its mark (pid %d)" % p["pid"])
            if key in seen_tests or (parent is not None and (marked.get(parent["pid"]) or {}).get(ENV_ROW) == row_id
                                     and (marked.get(parent["pid"]) or {}).get(ENV_RUN) == run_id):
                continue                    # a child of the same run: reported once, at the run's first process
            seen_tests.add(key)
            row = rows.get(row_id)
            last = row.get("last_run") if row and isinstance(row.get("last_run"), dict) else {}
            entry = dict(pid=p["pid"], row=row_id, run_id=run_id, how="carries the runner's mark",
                         command=_short(p["cmdline"]))
            test_processes.append(entry)
            if row is None:
                mismatches.append(dict(kind="test process without a row", row=row_id, pid=p["pid"],
                                       text="Process %d carries the mark of test %s, and the registry holds no row "
                                            "with that id. Command: %s" % (p["pid"], row_id, entry["command"])))
            elif row.get("status") != "running" or (run_id and last.get("run_id") != run_id):
                mismatches.append(dict(kind="test process without a running row", row=row_id, pid=p["pid"],
                                       text="Process %d runs test %s (run %s), and its row says %s%s. Command: %s"
                                            % (p["pid"], row_id, run_id, row.get("status"),
                                               "" if row.get("status") != "running" else
                                               " for another run (%s)" % last.get("run_id"), entry["command"])))
            continue
        if mine.get(ENV_DEV) or any((marked.get(a["pid"]) or {}).get(ENV_DEV) for a in line[1:]):
            text = mine.get(ENV_DEV) or next((marked[a["pid"]][ENV_DEV] for a in line[1:]
                                              if (marked.get(a["pid"]) or {}).get(ENV_DEV)), "")
            if parent is None or not (marked.get(parent["pid"]) or {}).get(ENV_DEV):
                owner, _, purpose = text.partition("|")
                development.append(dict(pid=p["pid"], owner=owner, purpose=purpose, command=_short(p["cmdline"]),
                                        since=tr.clock(p["created"])))
            continue
        if is_test_runner(p):
            continue                        # the runner itself: the job it starts carries the marks
        if p["pid"] in trainer_ids or any(a["pid"] in trainer_ids for a in line[1:]):
            continue                        # production's trainer and the processes it starts
        legacy = next((legacy_runner_row(a) for a in line if legacy_runner_row(a)), None)
        if legacy:
            note_row(legacy, "a runner of the older kind whose command line names it (pid %d)" % p["pid"])
            key = ("legacy", legacy)
            if key not in seen_tests:
                seen_tests.add(key)
                entry = dict(pid=p["pid"], row=legacy, run_id=None, how="a runner of the older kind names the row",
                             command=_short(p["cmdline"]))
                test_processes.append(entry)
                row = rows.get(legacy)
                if row is None or row.get("status") != "running":
                    mismatches.append(dict(
                        kind="test process without a running row", row=legacy, pid=p["pid"],
                        text="Process %d runs under a runner that names test %s, and %s. Command: %s"
                             % (p["pid"], legacy, "the registry holds no row with that id" if row is None else
                                "its row says %s" % row.get("status"), entry["command"])))
            continue
        if any(is_legacy_capped(a) for a in line):
            first = next(a for a in line if is_legacy_capped(a))
            key = ("capped", first["pid"])
            if key not in seen_tests:
                seen_tests.add(key)
                development.append(dict(pid=first["pid"], owner="not recorded (a capped run of the older kind)",
                                        purpose="not recorded", command=_short(first["cmdline"]),
                                        since=tr.clock(first["created"])))
            continue
        scheduler = next((a for a in line[1:] if SCHEDULER_MODULE in a.get("cmdline", [])), None)
        task = scheduled_task(p) if scheduler is not None else None
        if task:
            note_row(task, "the ability scheduler's process for it (pid %d)" % p["pid"])
            key = ("scheduled", task)
            if key not in seen_tests:
                seen_tests.add(key)
                entry = dict(pid=p["pid"], row=task, run_id=None, how="started by the ability scheduler",
                             command=_short(p["cmdline"]))
                test_processes.append(entry)
                row = rows.get(task)
                if row is None or row.get("status") != "running":
                    mismatches.append(dict(
                        kind="test process without a running row", row=task, pid=p["pid"],
                        text="Process %d is the ability scheduler's check %s, and %s. Command: %s"
                             % (p["pid"], task, "the registry holds no row with that id" if row is None else
                                "its row says %s" % row.get("status"), entry["command"])))
            continue
        pause_runner = next((name for a in line[1:] for name in _script_names(a) if name in PAUSE_RUNNERS), None)
        if pause_runner and not any(name in PAUSE_RUNNERS for name in _script_names(p)):
            holders = [i for i, r in rows.items() if r.get("status") == "running"
                       and isinstance(r.get("last_run"), dict) and r["last_run"].get("runner") == pause_runner]
            key = ("pause", pause_runner)
            for i in holders:
                note_row(i, "a job process under %s (pid %d)" % (pause_runner, p["pid"]))
            if key not in seen_tests:
                seen_tests.add(key)
                entry = dict(pid=p["pid"], row=holders[0] if len(holders) == 1 else None, run_id=None,
                             how="a job of %s" % pause_runner, command=_short(p["cmdline"]))
                test_processes.append(entry)
                if not holders:
                    mismatches.append(dict(
                        kind="test process without a running row", row=None, pid=p["pid"],
                        text="Process %d is a job of %s, and no row written by that runner says running. Command: %s"
                             % (p["pid"], pause_runner, entry["command"])))
            continue
        why = signature_of(p)
        if why and not any(signature_of(a) for a in line[1:]):
            entry = dict(pid=p["pid"], row=None, run_id=None, how=why, command=_short(p["cmdline"]))
            test_processes.append(entry)
            mismatches.append(dict(
                kind="test process without a row", row=None, pid=p["pid"],
                text="Process %d (started %s) is a test process by its command line (%s) and carries no runner's "
                     "mark: it was started without the runner, so no row says it is running. Command: %s"
                     % (p["pid"], tr.clock(p["created"]), why, entry["command"])))

    # ---- every running row has a live process
    baseline = load_baseline(code_root)
    hold_now = None                          # training_hold(root), read once when a production segment needs it
    for row_id, row in rows.items():
        status = row.get("status")
        last = row.get("last_run") if isinstance(row.get("last_run"), dict) else {}
        state = tr.run_state(row)
        if status == "running":
            how = None
            lost_why = None
            if alive(last.get("pid"), last.get("pid_created"), processes):
                how = "its job process %s is alive" % last.get("pid")
            elif last.get("pid") is None and alive(last.get("runner_pid"), last.get("runner_pid_created"), processes) \
                    and last.get("runner_pid") is not None:
                how = "its runner process %s is alive and has not yet written the job's process" % last["runner_pid"]
            elif alive(last.get("runner_pid"), last.get("runner_pid_created"), processes) \
                    and last.get("runner_pid") is not None and last.get("resource_class") != "PRODUCTION_SEGMENT":
                # A TIME BOUND ON "WRITING ITS END" (the dashboard review of Oct 5, 2026, finding L1): a runner writes a
                # job's end within seconds of the job's last process; a runner that started a later row's job has
                # moved on, and a job past its own time limit by WRITING_END_S cannot still be ending
                lost_why = writing_end_over(row_id, last, rows, now)
                if lost_why is None:
                    how = "its runner process %s is alive (the job process %s is gone: the runner is writing its end)" \
                          % (last["runner_pid"], last.get("pid"))
            run_name = named_run(row)
            # a production segment: stated by its runner, or (a row written before Oct 5, 2026) a last run with no
            # process recorded whose log sits inside a run folder
            segment = last.get("resource_class") == "PRODUCTION_SEGMENT" or bool(
                run_name and last.get("pid") is None and last.get("runner_pid") is None)
            if segment and run_name:
                how = None
                trainer = next((t for t in trainers if run_name in trainer_runs(t)), None)
                if trainer is not None:
                    how = "the trainer of run %s is alive (pid %d)" % (run_name, trainer["pid"])
            if how is None and lost_why is None and not (segment and run_name) and found_rows.get(row_id):
                how = found_rows[row_id][0]
            # PROCESS STATE: RUNNING (a live process), HELD (a production segment of the run training is held in,
            # while no production trainer is alive: the segment's process does not exist while training is held),
            # LOST (no live process otherwise). A segment of ANOTHER run than the held one ended at a relaunch before
            # the hold, so the hold does not explain it (the dashboard review of Oct 5, 2026, finding L3)
            held_run = None
            if how is None and segment and run_name and not trainers:
                hold_now = hold_now if hold_now is not None else training_hold(root)
                held_run = hold_now.get("active_run")
            process_state = "RUNNING" if how is not None else \
                "HELD" if segment and run_name and not trainers and holds_run(hold_now, run_name) else "LOST"
            hold = hold_now if process_state == "HELD" else None
            running_rows.append(dict(id=row_id, alive=how is not None, how=how, started=last.get("started"),
                                     owner=last.get("owner"),
                                     resource_class=last.get("resource_class") or tr.default_resource_class(row),
                                     production_run=run_name if segment else None, state=process_state,
                                     hold=hold, held_text=held_text(hold) if hold else None))
            if how is None and process_state == "HELD":
                mismatches.append(dict(
                    kind="production segment held", row=row_id, pid=None,
                    text="Row %s says running for the production run %s (since %s). HELD: %s The row's status is "
                         "still running, and no process of it exists while training is held. The coordinator writes "
                         "its end (test_runner finish %s --outcome STOPPED --basis TEXT --by NAME); the relaunch "
                         "writes the new run's start (the deploy script's --row %s)."
                         % (row_id, run_name, last.get("started") or "an unrecorded time", held_text(hold), row_id,
                            row_id)))
            elif how is None:
                if segment and run_name and not trainers:
                    text = ("Row %s says running for the production run %s (since %s), and training is held in run %s: "
                            "run %s ended at a relaunch before the hold and its end was not written (test_runner finish "
                            "%s --outcome STOPPED --basis TEXT --by NAME writes it)." % (
                                row_id, run_name, last.get("started") or "an unrecorded time",
                                held_run or "no run on record", run_name, row_id))
                elif segment and run_name:
                    text = ("Row %s says running for the production run %s (since %s), and no trainer process of "
                            "that run is alive; the trainer alive is of run %s." % (
                                row_id, run_name, last.get("started") or "an unrecorded time",
                                ", ".join(sorted({r for t in trainers for r in trainer_runs(t)}))))
                elif lost_why is not None:
                    text = ("Row %s says running (since %s), its job process %s is gone and its end is not written: %s."
                            % (row_id, last.get("started") or "an unrecorded time", last.get("pid"), lost_why))
                elif last.get("pid") is None and last.get("runner_pid") is None:
                    text = ("Row %s says running (since %s, written by %s) with no process recorded, and no live "
                            "process was matched to it." % (row_id, last.get("started") or "an unrecorded time",
                                                            last.get("runner") or "an unnamed writer"))
                else:
                    text = ("Row %s says running (since %s), and its process %s (runner %s) is gone: the run ended "
                            "without its end being written." % (row_id, last.get("started") or "an unrecorded time",
                                                                last.get("pid"), last.get("runner_pid")))
                mismatches.append(dict(kind="running row without a live process", row=row_id, pid=last.get("pid"),
                                       text=text))
        # ---- no runner status without the runner's record
        if status in tr.RUNNER_STATUSES:
            if tr.sealed(row):
                expected = "running" if state == "running" else tr.STATUS_OF_OUTCOME.get(state)
                if expected != status:
                    mismatches.append(dict(kind="status differs from the runner's record", row=row_id, pid=None,
                                           text="Row %s says %s, and its runner's sealed record says %s: the status "
                                                "was changed after the runner wrote it." % (row_id, status, state)))
                elif state in tr.OUTCOMES and row.get("outcome") != state:
                    mismatches.append(dict(kind="outcome differs from the runner's record", row=row_id, pid=None,
                                           text="Row %s shows outcome %s, and its runner's sealed record says %s."
                                                % (row_id, row.get("outcome"), state)))
            else:
                kind, text = unsealed_judgement(row_id, row, baseline)
                if kind == "unverified":
                    unverified.append(dict(row=row_id, text=text))
                else:
                    mismatches.append(dict(kind="status without the runner's record", row=row_id, pid=None,
                                           text=text))
        elif state == "running" and tr.sealed(row):
            mismatches.append(dict(kind="status changed by hand during a run", row=row_id, pid=last.get("pid"),
                                   text="Row %s says %s, and its runner's sealed record says the run is still "
                                        "running: the status was changed by hand before the runner wrote the end."
                                        % (row_id, status)))
    ok = not mismatches
    # WHAT THE AUDIT SEES, stated with its result (the dashboard review of Oct 5, 2026, finding F10): a test started
    # with no runner outside the signatures is not seen, and a development run is listed as a warning, not checked
    sentence = (("%d running %s, each with a live process; %d live %s, each with its running row. "
                 % (len(running_rows), "row" if len(running_rows) == 1 else "rows", len(test_processes),
                    "test process" if len(test_processes) == 1 else "test processes")) if ok else
                "%d %s between the test processes and the registry's rows. " % (
                    len(mismatches), "mismatch" if len(mismatches) == 1 else "mismatches")) + SEEN_TEXT + (
        " %d development %s without a row %s listed as %s." % (
            len(development), "run" if len(development) == 1 else "runs", "is" if len(development) == 1 else "are",
            "a warning" if len(development) == 1 else "warnings") if development else "")
    warnings = [dict(kind="development run", row=None, pid=d["pid"],
                     text="Process %s runs without a registry row as a development run (owner: %s; purpose: %s; since "
                          "%s): it has no row, no time limit from a row and no recorded end. Command: %s"
                          % (d["pid"], d.get("owner") or "not recorded", d.get("purpose") or "not recorded",
                             d.get("since") or "an unrecorded time", d.get("command")))
                for d in development]
    return dict(available=True, ok=ok, read_at=now, read_at_text=tr.clock(now), sentence=sentence,
                seen=SEEN_TEXT, warnings=warnings,
                mismatches=mismatches, running_rows=running_rows, test_processes=test_processes,
                development_runs=development, unverified=unverified,
                trainers=[dict(pid=t["pid"], runs=trainer_runs(t), since=tr.clock(t["created"])) for t in trainers],
                baseline=dict(taken_at=baseline.get("taken_at"), seal_required_from=baseline.get("seal_required_from"),
                              rows=len(baseline.get("rows", {}))) if baseline else None)


