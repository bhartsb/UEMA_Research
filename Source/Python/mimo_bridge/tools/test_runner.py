"""The one runner entry point of the test registry, and the audit of test processes against running rows.

The operator's recovery directive of Oct 5, 2026, section 8: "The registry must be generated by execution, not
maintained by memory." tools/test_registry.py holds the rows and the two functions that write a run's start and end;
this module starts a row's job, watches it, ends it at its limits, and checks the machine against the rows.

    python -m mimo_bridge.tools.test_runner run ROW_ID [options] -- COMMAND ...
    python -m mimo_bridge.tools.test_runner dev --owner NAME --purpose "TEXT" -- COMMAND ...
    python -m mimo_bridge.tools.test_runner audit [--json]
    python -m mimo_bridge.tools.test_runner stop ROW_ID --by NAME --reason "TEXT"
    python -m mimo_bridge.tools.test_runner close ROW_ID --by NAME --reason "TEXT"
    python -m mimo_bridge.tools.test_runner segment-start ROW_ID --run RUN_FOLDER --pid PID [--checkpoint C]
    python -m mimo_bridge.tools.test_runner finish ROW_ID --outcome PASS|FAIL|INVALID|STOPPED --basis "TEXT" --by NAME
                                                     (a production segment only)
    python -m mimo_bridge.tools.test_runner queue|unblock ROW_ID --by NAME
    python -m mimo_bridge.tools.test_runner block ROW_ID --reason "TEXT" --waits-on "TEXT" --by NAME
    python -m mimo_bridge.tools.test_runner cancel ROW_ID --reason "TEXT" --by NAME
    python -m mimo_bridge.tools.test_runner follow-up ROW_ID --text "TEXT" --owner NAME --by NAME
    python -m mimo_bridge.tools.test_runner baseline [--write] [--seal-required-from "Oct 6, 2026 9:00 AM PDT"]

Every subcommand takes --registry PATH (default: the registry of this module's checkout).

RUN, in order:
 1. REFUSES before anything starts (exit code 4) when: no single complete row has the id (test_registry.refusal:
    missing, duplicate, incomplete, cancelled); the row carries a block (test_registry.block_row); the row's last run
    is still running with a live process; the row needs training stopped (its resource class is TEST_WINDOW) while a
    production trainer process is alive; or the defect register's 24-hour rule holds the row back
    (defect_register.runner_gate).
 2. WRITES THE START (test_registry.job_started): status running, start time, the commit and dirty flag of the
    command's working directory, the checkpoint, the owner, the machine resource class, this runner's process id and
    its creation time. When that write fails the command is never started: no test process without its running row.
 3. STARTS THE COMMAND with UEMA_TEST_ROW and UEMA_TEST_RUN in its environment (every process the command starts
    inherits them: the audit finds a row's processes by them), its output in the log file, then writes the job's
    own process id and creation time (test_registry.job_process).
 4. WAITS, looking once a second for: the command's end; the row's time limit (cost.time_limit_s, or --timeout);
    a stop request (the `stop` subcommand's file); and, for a TEST_WINDOW row, a production trainer process that
    started. The last three end the command's whole process tree.
 5. WRITES THE END (test_registry.finish_job): PASS, FAIL, INVALID or STOPPED (test_registry.read_outcome: the result
    file's verdict key, else the exit code), the end time, the result file, the result and the next action.
 Exit code: 0 PASS, 1 FAIL, 2 INVALID, 3 STOPPED, 4 refused.

DEV runs a command that is not a registered test (a unit-test run while building, a one-off reading). It carries
UEMA_DEV_RUN (owner and purpose) in its environment and is appended to the development-run log, so the audit lists it
as a development run instead of a test process without a row. It writes no registry row.

AUDIT (audit(), also served inside GET /api/tests) checks both directions and returns every mismatch as an error:
 - every row whose status is running has a live process: its recorded job process or runner process (same process
   id and creation time), a process carrying its UEMA_TEST_ROW and run id, a runner of the older kind whose command
   line names the row, or, for a production segment (last_run.production_run, or a last_run log path inside a run
   folder), a trainer process whose command line names that run folder;
 - every live test process has a running row. A test process is: a process carrying UEMA_TEST_ROW; a process under a
   runner of the older kind (`..._registry.py run ROW_ID`), the ability scheduler or a pause runner; and a process
   carrying no mark whose command line is a test's by TEST SIGNATURES below. Not recognised: a test started with no
   runner from a folder the signatures do not name. That gap is the reason every test goes through `run` or `dev`;
   the audit's sentence states it (SEEN_TEXT), and each development run is listed as a warning with its owner and
   purpose (the dashboard review of Oct 5, 2026, finding F10).
 - no runner status without the runner's record: status running, done or failed whose last_run does not carry a
   verified seal is an error, unless the row holds that same status and last_run in the baseline file's own list
   (rows as they stood before the seal existed; listed under "unverified"). The date a typed last run carries does
   not matter (finding F5).
 - a running row whose job process is gone while its runner lives is LOST once that runner has started a later row's
   job or the job is past its time limit by WRITING_END_S (finding L1); a production segment's row is HELD only when
   its run is the run training is held in, else LOST (finding L3).

TEST SIGNATURES for a process without a mark (python, pytest or py processes only):
 - a command line that names a .py file inside a folder docs/gain_of_function_v<N>/ of any checkout, unless the file's
   name is a runner's, a registry writer's, a watch program's or a deploy script's (NOT_TEST_SCRIPTS);
 - a trainer (mimo_bridge.train_mimo) whose command line names no folder under Saved/mimo_bridge/experiments;
 - pytest (python -m pytest, or the pytest program).
"""
