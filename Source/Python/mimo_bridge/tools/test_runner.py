def refusal(row_id, path=None, root=None, check_rule=True, processes=None, segment=False, lifecycle_supported=False, preserve_production=False):
    """Why the runner will not start row `row_id` now, or None (RUN step 1 in the module text). `segment` is true
    for a production segment's start: its process is the trainer, so a live trainer does not refuse it."""
    path = Path(path or tr.registry_path(root))
    try:
        data = tr.load(path)
    except tr.RegistryError as exc:
        return "the test registry cannot be read (%s); every job is refused until it can" % exc
    # the row, its block and the defect register's 24-hour rule: the registry's one refusal, which the pause runners
    # and the ability scheduler read too (test_registry.refusal)
    why = tr.refusal(row_id, data=data, path=path, check_rule=check_rule, lifecycle_supported=lifecycle_supported,
                     preserve_production=preserve_production)
    if why:
        return why
    row = tr.rows_with_id(data, row_id)[0]
    last = row.get("last_run") if isinstance(row.get("last_run"), dict) else {}
    if row.get("status") == "running":
        if alive(last.get("pid"), last.get("pid_created")) or alive(last.get("runner_pid"),
                                                                    last.get("runner_pid_created")):
            return "its row says running and its process %s is alive: one run of a row at a time" % (
                last.get("pid") or last.get("runner_pid"))
        return ("its row says running and no process of that run is alive: close that run first (test_runner close "
                "%s) so its end is written" % row_id)
    if tr.default_resource_class(row) == "TEST_WINDOW" and not segment:
        trainers = production_trainers(scan_processes() if processes is None else processes)
        if trainers:
            return ("its row needs training stopped (cost.training_stopped is true) and a production trainer "
                    "process is alive (pid %d, run %s)" % (trainers[0]["pid"], ", ".join(trainer_runs(trainers[0]))))
    return None


def end_tree(pid, timeout=30) -> int:
    """End process `pid` and every process under it; returns how many were ended."""
    import psutil
    try:
        root = psutil.Process(int(pid))
    except psutil.Error:
        return 0
    tree = root.children(recursive=True) + [root]
    for p in tree:
        try:
            p.kill()
        except psutil.Error:
            pass
    psutil.wait_procs(tree, timeout=timeout)
    return len(tree)


class Run:
    """One run of one row: start() writes the start (or raises Refused), job_process() writes the job's process,
    finish() writes the end. A wrapper that starts the command itself (the agents' capped runner) uses the three; the
    `run` subcommand uses run_command(), which also watches the limits."""

    def __init__(self, row_id, path, run_id, started, log):
        self.row_id, self.path, self.run_id, self.started, self.log = row_id, Path(path), run_id, started, log
        self.finished = None

    @classmethod
    def start(cls, row_id, path=None, *, runner="test_runner.py run", owner=None, checkpoint=None,
              resource_class=None, device=None, log=None, command=None, cwd=None, root=None, check_rule=True,
              production_run=None, pid=None, time_limit_s=None, lifecycle_supported=False):
        path = Path(path or tr.registry_path(root))
        why = refusal(row_id, path=path, root=root, check_rule=check_rule,
                      segment=resource_class == "PRODUCTION_SEGMENT", lifecycle_supported=lifecycle_supported,
                      preserve_production=bool(resource_class == "PRODUCTION_SEGMENT" and production_run and pid))
        if why:
            raise Refused(why)
        started = time.time()
        run_id = tr.new_run_id(row_id, started)
        failed = tr.job_started(row_id, started=started, log=log, runner=runner, path=path, owner=owner,
                                checkpoint=checkpoint, resource_class=resource_class, device=device,
                                command=command, run_id=run_id, cwd=cwd, production_run=production_run, pid=pid,
                                time_limit_s=time_limit_s)
        if failed:
            raise Refused("the start could not be written into the row, so the job was not started: %s" % failed)
        return cls(row_id, path, run_id, started, log)

    def env(self, base=None) -> dict:
        """The environment the job's process gets: `base` (this process's when None) plus the run's two marks."""
        out = dict(os.environ if base is None else base, **{ENV_ROW: self.row_id, ENV_RUN: self.run_id})
        data = tr.load(self.path)
        row = tr.rows_with_id(data, self.row_id)[0]
        if data.get("file_lifecycle_policy"):
            from . import file_lifecycle
            last = row.get("last_run", {})
            if last.get("run_id") != self.run_id:
                raise ValueError("run identity changed before output setup")
            _, evidence, temporary = file_lifecycle.locations(data["file_lifecycle_policy"], last["file_lifecycle"]["declaration"])
            temporary.mkdir(parents=True, exist_ok=True)
            out.update(TEMP=str(temporary), TMP=str(temporary), TMPDIR=str(temporary),
                       PYTEST_DEBUG_TEMPROOT=str(temporary), UEMA_EVIDENCE_DIR=str(evidence))
        return out

    def job_process(self, pid):
        return tr.job_process(self.row_id, pid, path=self.path, run_id=self.run_id)

    def finish(self, exit_code=None, *, stopped=None, not_started=None, root=None, state=None, judged_by=None,
               result_file=None):
        """Write the run's end; returns (why the write failed or None, the state written or None)."""
        self.finished = tr.finish_job(self.row_id, exit_code=exit_code, started=self.started, log=self.log,
                                      path=self.path, stopped=stopped, not_started=not_started, run_id=self.run_id,
                                      root=root, state=state, judged_by=judged_by, result_file=result_file)
        return self.finished


def _checkpoint_in(command):
    """The checkpoint a command line names: the value after --checkpoint or --resume, else None."""
    for flag in ("--checkpoint", "--resume"):
        if flag in command[:-1]:
            return command[command.index(flag) + 1]
    return None


def run_command(row_id, command, *, path=None, root=None, log=None, owner=None, checkpoint=None, resource_class=None,
                device=None, timeout_s=None, cwd=None, env=None, threads=None, end_when_trainer_starts=None,
                poll_s=1.0, check_rule=True, runner="test_runner.py run", popen=None):
    """RUN (the module text): returns (exit code of this runner, the state written or None, the log's path or None).
    Raises nothing for a refusal: it returns (EXIT_REFUSED, None, None) after printing why."""
    path = Path(path or tr.registry_path(root))
    command = [str(x) for x in command]
    if not command:
        print("refused: no command was given after --", flush=True)
        return EXIT_REFUSED, None, None
    try:
        row = tr.rows_with_id(tr.load(path), row_id)
        row = row[0] if len(row) == 1 else {}
    except tr.RegistryError:
        row = {}
    if log is None:
        if row.get("file_lifecycle"):
            log = Path(row["file_lifecycle"]["evidence_dir"]) / "runner.log"
        else:
            log = runs_dir() / "logs" / str(row_id) / (time.strftime("%Y%m%d_%H%M%S") + "_%d.log" % os.getpid())
    if row.get("file_lifecycle"):
        from . import file_lifecycle
        if not file_lifecycle.inside(log, row["file_lifecycle"]["evidence_dir"]):
            print("refused: runner log must stay inside the declared evidence folder", flush=True)
            return EXIT_REFUSED, None, None
    log = Path(log)
    # THE ROW'S TIME LIMIT IS THE JOB'S LIMIT (the dashboard review of Oct 5, 2026, finding L2): --timeout may shorten
    # it, never lengthen it; the limit the run used is written into its start record
    cost = row.get("cost") if isinstance(row.get("cost"), dict) else {}
    row_limit = cost.get("time_limit_s") if tr._number(cost.get("time_limit_s")) and cost["time_limit_s"] > 0 else None
    why = timeout_refusal(timeout_s, row_limit)
    if why:
        print("refused: %s" % why, flush=True)
        return EXIT_REFUSED, None, None
    limit = timeout_s if timeout_s else row_limit
    try:
        run = Run.start(row_id, path=path, runner=runner, owner=owner,
                        checkpoint=checkpoint or _checkpoint_in(command), resource_class=resource_class,
                        device=device, log=log, command=command, cwd=cwd, root=root, check_rule=check_rule,
                        time_limit_s=limit, lifecycle_supported=True)
    except Refused as exc:
        print("refused: %s" % exc, flush=True)
        return EXIT_REFUSED, None, None
    watch_trainer = (tr.default_resource_class(row) == "TEST_WINDOW" if end_when_trainer_starts is None
                     else bool(end_when_trainer_starts))
    try:
        child_env = run.env(env)
        if row.get("file_lifecycle") and child_env.get("UEMA_EVIDENCE_DIR"):
            from . import file_lifecycle
            if not file_lifecycle.inside(log, child_env["UEMA_EVIDENCE_DIR"]):
                raise ValueError("log disagrees with the claimed output folder")
    except (OSError, ValueError, KeyError) as exc:
        _, state = run.finish(not_started="file output setup failed: %s" % exc)
        return EXIT_OF_OUTCOME.get(state, 2), state, None
    child_env.setdefault("PYTHONUNBUFFERED", "1")
    if threads:
        for name in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
            child_env[name] = str(int(threads))
    if device != "gpu":
        child_env.setdefault("CUDA_VISIBLE_DEVICES", "-1")
    stopped = not_started = code = None
    try:
        log.parent.mkdir(parents=True, exist_ok=True)
        stream = log.open("wb")
    except OSError as exc:
        _, state = run.finish(not_started="not started: the log file %s could not be opened (%s)" % (log, exc))
        print("job %s %s: the log file could not be opened" % (row_id, state), flush=True)
        return EXIT_OF_OUTCOME.get(state, 2), state, None
    with stream:
        flags = subprocess.BELOW_NORMAL_PRIORITY_CLASS if os.name == "nt" else 0
        try:
            proc = (popen or subprocess.Popen)(command, cwd=None if cwd is None else str(cwd), env=child_env,
                                               stdout=stream, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                                               creationflags=flags)
        except (OSError, ValueError) as exc:
            not_started = "not started: the command could not be started (%s: %s)" % (type(exc).__name__, exc)
            proc = None
        if proc is not None:
            why = run.job_process(proc.pid)
            if why:
                print("the job's process id could not be written into the row: %s" % why, flush=True)
            deadline = None if not limit else run.started + float(limit)
            request = stop_file(run.run_id)
            while True:
                try:
                    code = proc.wait(timeout=poll_s)
                    break
                except subprocess.TimeoutExpired:
                    pass
                except KeyboardInterrupt:
                    stopped = "stopped: the runner was interrupted from its console"
                if stopped is None and deadline is not None and time.time() > deadline:
                    stopped = "stopped: its time limit of %s s passed" % tr._number_text(limit)
                if stopped is None and request.is_file():
                    try:
                        asked = json.loads(request.read_text(encoding="utf-8"))
                    except (OSError, ValueError):
                        asked = {}
                    stopped = "stopped: a stop was requested by %s (%s)" % (asked.get("by") or "an unnamed person",
                                                                           asked.get("reason") or "no reason given")
                if stopped is None and watch_trainer and production_trainers(scan_processes()):
                    stopped = "stopped: a production trainer process started while this job needed training stopped"
                if stopped is not None:
                    ended = end_tree(proc.pid)
                    stopped += "; %d %s ended" % (ended, "process" if ended == 1 else "processes")
                    try:
                        code = proc.wait(timeout=30)
                    except subprocess.TimeoutExpired:
                        code = None
                    break
    why, state = run.finish(code, stopped=stopped, not_started=not_started, root=root)
    if why:
        print("THE END COULD NOT BE WRITTEN INTO THE ROW: %s. The job ended with exit code %s; its row still says "
              "running, which the audit reports." % (why, code), flush=True)
        return 2, None, log
    print("job %s: %s (exit code %s); log %s" % (row_id, state, code, log), flush=True)
    return EXIT_OF_OUTCOME.get(state, 2), state, log


def dev_run(command, owner, purpose, *, cwd=None, env=None, threads=None, popen=None):
    """DEV (the module text): the command with UEMA_DEV_RUN in its environment, one line in the development-run log
    at its start and one at its end; returns the command's exit code."""
    if not str(owner or "").strip() or not str(purpose or "").strip():
        print("refused: a development run needs --owner and --purpose", flush=True)
        return EXIT_REFUSED
    command = [str(x) for x in command]
    child_env = dict(os.environ if env is None else env)
    child_env[ENV_DEV] = "%s|%s" % (str(owner).replace("|", "/"), str(purpose).replace("|", "/"))
    child_env.pop(ENV_ROW, None)
    child_env.pop(ENV_RUN, None)
    if threads:
        for name in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
            child_env[name] = str(int(threads))
    record = runs_dir() / "development_runs.jsonl"
    started = time.time()

    def note(**more):
        try:
            record.parent.mkdir(parents=True, exist_ok=True)
            with record.open("a", encoding="utf-8") as stream:
                stream.write(json.dumps(dict(owner=owner, purpose=purpose, command=command, started=tr.clock(started),
                                             **more)) + "\n")
        except OSError:
            pass
    flags = subprocess.BELOW_NORMAL_PRIORITY_CLASS if os.name == "nt" else 0
    proc = (popen or subprocess.Popen)(command, cwd=None if cwd is None else str(cwd), env=child_env,
                                       creationflags=flags)
    note(event="started", pid=proc.pid)
    try:
        code = proc.wait()
    except KeyboardInterrupt:
        end_tree(proc.pid)
        code = proc.wait()
    note(event="ended", pid=proc.pid, exit_code=code, ended=tr.clock(), seconds=round(time.time() - started, 1))
    return code


def request_stop(row_id, by, reason, path=None, root=None):
    """STOP: ask the row's live runner to end its job (a stop-request file the runner reads within a second). When
    the run's runner is gone, or is a runner of the older kind, end the recorded job process tree here and write
    STOPPED. Returns a plain sentence saying what was done; raises Refused when the row is not running."""
    path = Path(path or tr.registry_path(root))
    rows = tr.rows_with_id(tr.load(path), row_id)
    if len(rows) != 1 or rows[0].get("status") != "running":
        raise Refused("row %s is not running" % row_id)
    last = rows[0].get("last_run") if isinstance(rows[0].get("last_run"), dict) else {}
    if last.get("run_id") and alive(last.get("runner_pid"), last.get("runner_pid_created")) \
            and str(last.get("runner") or "").startswith("test_runner.py"):
        request = stop_file(last["run_id"])
        request.parent.mkdir(parents=True, exist_ok=True)
        request.write_text(json.dumps(dict(by=by, reason=reason, at=tr.clock())), encoding="utf-8")
        return "stop requested: runner %s ends the job and writes STOPPED" % last["runner_pid"]
    ended = end_tree(last["pid"]) if alive(last.get("pid"), last.get("pid_created")) else 0
    why, state = tr.finish_job(row_id, path=path, run_id=last.get("run_id"), root=root,
                               stopped="stopped by %s (%s); %d %s ended; no live runner of this module owned the "
                                       "run" % (by, reason, ended, "process" if ended == 1 else "processes"))
    if why:
        raise Refused("the stop could not be written: %s" % why)
    return "%d %s ended; row %s now says %s" % (ended, "process" if ended == 1 else "processes", row_id, state)


def close_run(row_id, by, reason, path=None, root=None, processes=None):
    """CLOSE: write STOPPED into a row that says running while no process of its run is alive (the audit's "running
    row without a live process"). Refused while a process of the run is alive: `stop` ends that. Returns the state
    written."""
    path = Path(path or tr.registry_path(root))
    data = tr.load(path)
    found = audit(path=path, data=data, root=root, processes=processes)
    entry = next((r for r in found["running_rows"] if r["id"] == row_id), None)
    if entry is None:
        raise Refused("row %s is not running" % row_id)
    if entry["alive"]:
        raise Refused("row %s has a live process (%s): end it with `stop` instead" % (row_id, entry["how"]))
    row = tr.rows_with_id(data, row_id)[0]
    last = row.get("last_run") if isinstance(row.get("last_run"), dict) else {}
    why, state = tr.finish_job(row_id, path=path, run_id=last.get("run_id"), root=root,
                               started=last.get("started_at") or tr.parse_clock(last.get("started")),
                               stopped="stopped: no process of this run was alive when %s closed it at %s (%s)"
                                       % (by, tr.clock(), reason))
    if why:
        raise Refused("the close could not be written: %s" % why)
    return state


def segment_start(row_id, run_folder, pid, *, path=None, root=None, checkpoint=None, owner=None,
                  runner="test_runner.py segment-start", check_rule=True):
    """A PRODUCTION SEGMENT'S START, called by the deploy script once its trainer runs: the row says running for run
    `run_folder`, with the trainer's process id and resource class PRODUCTION_SEGMENT. Raises Refused as `run` does."""
    run = Run.start(row_id, path=path, runner=runner, owner=owner, checkpoint=checkpoint,
                    resource_class="PRODUCTION_SEGMENT", device="gpu", log=str(Path(run_folder) / "trainer.log"),
                    root=root, check_rule=check_rule, production_run=str(run_folder), pid=pid)
    return run


def is_production_segment(row) -> bool:
    """True for a row whose running last_run is a segment of production training: its runner stated the resource
    class PRODUCTION_SEGMENT, or (a row written before Oct 5, 2026) its last run names a run folder and records no
    process (the audit's own test)."""
    last = row.get("last_run") if isinstance(row, dict) and isinstance(row.get("last_run"), dict) else {}
    return last.get("resource_class") == "PRODUCTION_SEGMENT" or bool(
        named_run(row) and last.get("pid") is None and last.get("runner_pid") is None)


def segment_finish(row_id, outcome, basis, by, *, path=None, root=None, result_file=None):
    """A PRODUCTION SEGMENT'S END: the outcome with the basis it was read from, written by the runner's own function.
    Refused for a row that is not running, and for a row that is not a production segment (is_production_segment):
    every other run's end is written by its own runner from its result file or exit code, and a run whose processes
    are gone is closed STOPPED with `close` (the dashboard review of Oct 5, 2026, finding F4: a PASS stated by a
    person for a test no runner judged was sealed like a runner's)."""
    if outcome not in tr.OUTCOMES:
        raise Refused("the outcome is not one of %s" % ", ".join(tr.OUTCOMES))
    if not str(basis or "").strip() or not str(by or "").strip():
        raise Refused("an outcome stated this way needs its basis and who states it")
    path = Path(path or tr.registry_path(root))
    rows = tr.rows_with_id(tr.load(path), row_id)
    if len(rows) != 1 or rows[0].get("status") != "running":
        raise Refused("row %s is not running" % row_id)
    last = rows[0].get("last_run") if isinstance(rows[0].get("last_run"), dict) else {}
    if not is_production_segment(rows[0]):
        raise Refused("row %s is not a production segment: its runner writes its end from its result file or its exit "
                      "code; a run whose processes are gone is closed STOPPED with `test_runner close %s`"
                      % (row_id, row_id))
    why, state = tr.finish_job(row_id, path=path, run_id=last.get("run_id"), root=root,
                               started=last.get("started_at") or tr.parse_clock(last.get("started")),
                               state=outcome, judged_by="stated by %s: %s" % (by, basis), result_file=result_file)
    if why:
        raise Refused("the end could not be written: %s" % why)
    return state


# ------------------------------------------------------------------------------------------ the command line
def _split(argv):
    if "--" in argv:
        at = argv.index("--")
        return argv[:at], argv[at + 1:]
    return argv, []


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    own, command = _split(argv)
    parser = argparse.ArgumentParser(prog="test_runner", description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=["run", "dev", "audit", "stop", "close", "segment-start", "finish", "queue",
                                           "unblock", "block", "cancel", "follow-up", "baseline"])
    parser.add_argument("row", nargs="?")
    parser.add_argument("--registry", help="the registry file (default: this checkout's)")
    parser.add_argument("--root", help="the checkout that holds Saved/ and the registry (default: this module's)")
    parser.add_argument("--owner")
    parser.add_argument("--purpose")
    parser.add_argument("--by")
    parser.add_argument("--reason")
    parser.add_argument("--waits-on")
    parser.add_argument("--text")
    parser.add_argument("--checkpoint")
    parser.add_argument("--resource-class", choices=sorted(tr.RESOURCE_CLASSES))
    parser.add_argument("--device", choices=["cpu", "gpu"])
    parser.add_argument("--log")
    parser.add_argument("--cwd")
    parser.add_argument("--timeout", type=float)
    parser.add_argument("--threads", type=int)
    parser.add_argument("--run", dest="run_folder")
    parser.add_argument("--pid", type=int)
    parser.add_argument("--outcome", choices=list(tr.OUTCOMES))
    parser.add_argument("--basis")
    parser.add_argument("--result-file")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--seal-required-from")
    parser.add_argument("--keep-running-beside-trainer", action="store_true",
                        help="run: do not end a TEST_WINDOW job when a production trainer starts")
    a = parser.parse_args(own)
    root = Path(a.root) if a.root else None
    path = Path(a.registry) if a.registry else tr.registry_path(root)
    needs_row = a.action not in ("dev", "audit", "baseline")
    if needs_row and not a.row:
        parser.error("%s needs a row id" % a.action)
    try:
        if a.action == "run":
            code, _state, _log = run_command(
                a.row, command, path=path, root=root, log=a.log, owner=a.owner, checkpoint=a.checkpoint,
                resource_class=a.resource_class, device=a.device, timeout_s=a.timeout, cwd=a.cwd, threads=a.threads,
                end_when_trainer_starts=False if a.keep_running_beside_trainer else None)
            return code
        if a.action == "dev":
            return dev_run(command, a.owner, a.purpose, cwd=a.cwd, threads=a.threads)
        if a.action == "audit":
            found = audit(path=path, root=root)
            if a.json:
                print(json.dumps(found, indent=1, ensure_ascii=False))
            else:
                print(found["sentence"])
                for m in found["mismatches"]:
                    print("MISMATCH (%s): %s" % (m["kind"], m["text"]))
                for u in found["unverified"]:
                    print("UNVERIFIED: %s" % u["text"])
                for d in found["development_runs"]:
                    print("development run: pid %s, owner %s, purpose %s" % (d["pid"], d["owner"], d["purpose"]))
            return 0 if found["ok"] else 1
        if a.action == "stop":
            print(request_stop(a.row, a.by or "", a.reason or "", path=path, root=root))
            return 0
        if a.action == "close":
            print("row %s now says %s" % (a.row, close_run(a.row, a.by or "", a.reason or "", path=path, root=root)))
            return 0
        if a.action == "segment-start":
            if not a.run_folder or a.pid is None:
                parser.error("segment-start needs --run and --pid")
            run = segment_start(a.row, a.run_folder, a.pid, path=path, root=root, checkpoint=a.checkpoint,
                                owner=a.owner)
            print("row %s says running for run %s (run id %s)" % (a.row, a.run_folder, run.run_id))
            return 0
        if a.action == "finish":
            print("row %s now says %s" % (a.row, segment_finish(a.row, a.outcome, a.basis, a.by, path=path, root=root,
                                                              result_file=a.result_file)))
            return 0
        if a.action == "baseline":
            made = make_baseline(tr.load(path), seal_required_from=a.seal_required_from)
            if a.write:
                target = baseline_path()
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(json.dumps(made, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
                print("baseline of %d rows written to %s at %s" % (len(made["rows"]), target, made["taken_at"]))
            else:
                print(json.dumps(made, indent=1, ensure_ascii=False))
            return 0
        by = a.by or ""
        if not by.strip():
            parser.error("%s needs --by (who writes it)" % a.action)
        why = (tr.queue_row(a.row, by, path=path) if a.action == "queue" else
               tr.unblock_row(a.row, by, path=path) if a.action == "unblock" else
               tr.block_row(a.row, a.reason, a.waits_on, by, path=path) if a.action == "block" else
               tr.cancel_row(a.row, a.reason, by, path=path) if a.action == "cancel" else
               tr.write_follow_up(a.row, a.text, a.owner, by, path=path))
        if why:
            print("refused: %s" % why)
            return EXIT_REFUSED
        print("%s written into row %s at %s" % (a.action, a.row, tr.clock()))
        return 0
    except Refused as exc:
        print("refused: %s" % exc)
        return EXIT_REFUSED
    except tr.RegistryError as exc:
        print("refused: %s" % exc)
        return EXIT_REFUSED


if __name__ == "__main__":
    sys.exit(main())
