"""Source mask constants -- integer-indexed replacement for string source masks.

Four states for each modality's data source, used by encoder_registry (skip
disabled), loss_manager (scale by source quality), and replay_buffer (storage).

Integer comparison is ~10x faster than string comparison in hot loops.
"""

# Source mask values (uint8-compatible)
SOURCE_REAL = 0       # Sensor data present this frame
SOURCE_STALE = 1      # Modality active but data not fresh (reusing cached token)
SOURCE_SYNTHETIC = 2  # Data generated by placeholder system
SOURCE_DISABLED = 3   # Encoder skips this modality entirely

# String-to-int mapping for migration from old Dict[str, str] masks
_STR_TO_INT = {
    "real": SOURCE_REAL,
    "stale": SOURCE_STALE,
    "synthetic": SOURCE_SYNTHETIC,
    "disabled": SOURCE_DISABLED,
}

# Int-to-string for diagnostics/logging
_INT_TO_STR = {v: k for k, v in _STR_TO_INT.items()}


def to_int(value) -> int:
    """Convert source mask value to int (accepts both str and int)."""
    if isinstance(value, int):
        return value
    return _STR_TO_INT.get(value, SOURCE_REAL)


def to_str(value) -> str:
    """Convert source mask value to str (accepts both str and int)."""
    if isinstance(value, str):
        return value
    return _INT_TO_STR.get(value, "real")


def training_source_masks(current_batch, target_batch, modalities):
    """Keep current-frame and next-frame source validity separate for training.

    Prediction targets belong to target_batch. Motor/gaze consumers retain the
    current batch's mask. Both use the native trainer's existing conservative
    reduction: any synthetic sample masks the modality; otherwise any stale
    sample makes it stale. Missing labels retain the existing real default.
    """
    rank = {"synthetic": 0, "stale": 1, "real": 2}
    labels = {0: "synthetic", 1: "stale", 2: "real"}

    def reduce(batch):
        masks = batch["source_masks"]
        return {
            mod: labels[min(rank.get(to_str((mask or {}).get(mod, "real")), 2)
                            for mask in masks)]
            for mod in modalities
        }

    return reduce(current_batch), reduce(target_batch)
